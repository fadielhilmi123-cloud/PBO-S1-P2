public class IlustrasiIncrement {
    public void tampilkan() {
        int x = 10;
        System.out.println("==========================");
        System.out.println("| IMPLEMENTASI INCREMENT |");
        System.out.println("==========================");
        System.out.println("Nilai awal: " + x);

        x++;
        System.out.println("Setelah x++: " + x);

        ++x;
        System.out.println("Setelah ++x: " + x);
        System.out.println("==========================");
    }
}

